/**
 * One-time devnet setup for Hobita.
 *
 *   node scripts/devnet-setup.mjs
 *
 * - loads the Solana CLI keypair (the same wallet Anchor deploys with)
 * - tops up devnet SOL if needed
 * - creates a 6-decimal test USDC mint where that wallet is the authority
 * - mints 10,000 test USDC to the wallet
 * - writes NEXT_PUBLIC_USDC_MINT and SOLANA_FAUCET_SECRET into .env.local
 *
 * The mint authority secret is the faucet key, so this is devnet-only.
 */
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import {
  Connection,
  Keypair,
  LAMPORTS_PER_SOL,
  clusterApiUrl,
} from "@solana/web3.js";
import {
  createMint,
  getOrCreateAssociatedTokenAccount,
  mintTo,
} from "@solana/spl-token";

const RPC = process.env.NEXT_PUBLIC_RPC_URL || clusterApiUrl("devnet");
const keypairPath =
  process.env.SOLANA_KEYPAIR ||
  path.join(os.homedir(), ".config", "solana", "id.json");

if (!fs.existsSync(keypairPath)) {
  console.error(`No keypair at ${keypairPath}. Run: solana-keygen new`);
  process.exit(1);
}

const payer = Keypair.fromSecretKey(
  Uint8Array.from(JSON.parse(fs.readFileSync(keypairPath, "utf8"))),
);
const connection = new Connection(RPC, "confirmed");

console.log("Wallet:", payer.publicKey.toBase58());

let balance = await connection.getBalance(payer.publicKey);
console.log("Balance:", balance / LAMPORTS_PER_SOL, "SOL");

if (balance < 0.5 * LAMPORTS_PER_SOL) {
  for (let attempt = 0; attempt < 3; attempt += 1) {
    try {
      console.log(`Requesting airdrop (attempt ${attempt + 1})…`);
      const signature = await connection.requestAirdrop(
        payer.publicKey,
        LAMPORTS_PER_SOL,
      );
      await connection.confirmTransaction(signature, "confirmed");
      balance = await connection.getBalance(payer.publicKey);
      if (balance >= 0.5 * LAMPORTS_PER_SOL) break;
    } catch (error) {
      console.warn("Airdrop failed:", error.message);
    }
  }
}

if (balance < 0.1 * LAMPORTS_PER_SOL) {
  console.error(
    "Not enough devnet SOL. Fund the wallet at https://faucet.solana.com and rerun.",
  );
  process.exit(1);
}

console.log("Creating test USDC mint (6 decimals)…");
const mint = await createMint(connection, payer, payer.publicKey, null, 6);
console.log("Mint:", mint.toBase58());

const ata = await getOrCreateAssociatedTokenAccount(
  connection,
  payer,
  mint,
  payer.publicKey,
);
const mintSignature = await mintTo(
  connection,
  payer,
  mint,
  ata.address,
  payer,
  10_000 * 1_000_000,
);
console.log("Minted 10,000 test USDC:", mintSignature);

const envPath = path.join(process.cwd(), ".env.local");
const existing = fs.existsSync(envPath) ? fs.readFileSync(envPath, "utf8") : "";
const lines = new Map();
for (const line of existing.split(/\r?\n/)) {
  const match = line.match(/^([A-Z0-9_]+)=(.*)$/);
  if (match) lines.set(match[1], match[2]);
}
lines.set("NEXT_PUBLIC_CLUSTER", "devnet");
lines.set("NEXT_PUBLIC_RPC_URL", "https://api.devnet.solana.com");
lines.set("NEXT_PUBLIC_USDC_MINT", mint.toBase58());
lines.set(
  "SOLANA_FAUCET_SECRET",
  JSON.stringify(Array.from(payer.secretKey)),
);

const output = [
  "# Generated by scripts/devnet-setup.mjs — devnet only, never commit.",
  ...Array.from(lines.entries()).map(([key, value]) => `${key}=${value}`),
  "",
].join("\n");
fs.writeFileSync(envPath, output);

console.log("\nWrote", envPath);
console.log("NEXT_PUBLIC_USDC_MINT=" + mint.toBase58());
console.log("\nNext: anchor keys sync && anchor build && anchor deploy");
